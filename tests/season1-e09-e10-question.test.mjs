import test from 'node:test';
import assert from 'node:assert/strict';
import * as E07 from '../e07-scene/scene-model.mjs';
import * as E09 from '../e09-scene/scene-model.mjs';
import * as E10 from '../authoring-labs/unnamed-story-model.mjs';
import {sevenSceneUpstream} from './fixtures/season1-e04-e09-paper.mjs';
import {questionSource,freshTrial,replayTrial,restoreTrial,dispatchTrial,viewTrial} from '../e10-scene/hill-question.mjs';

const move=(s,a)=>{assert.equal(E10.can(s,a),true,JSON.stringify(a));return E10.dispatch(s,a);};
test('E09 child-earned unanswered questions become a reversible E10 trace check, not historical evidence',()=>{
 const {e07,e08,e09}=sevenSceneUpstream(),source=questionSource(e07,e08,e09);
 assert.ok(source);assert.deepEqual(Object.keys(source.questions),['access','identity']);
 assert.equal(source.upperHillClosed,true);assert.equal(source.realAccessApproved,false);
 assert.equal(source.placeName,null);assert.deepEqual(source.unlocks,[]);
 let e10=move(E10.fresh(),{type:'start'}),trial=freshTrial();
 trial=dispatchTrial(trial,{type:'choose',question:'access'},source,e10);
 trial=dispatchTrial(trial,{type:'place',anchor:'notice_wall'},source,e10);
 trial=dispatchTrial(trial,{type:'compare'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,false);
 assert.match(viewTrial(trial,source,e10).feedback,/Not yet/);
 trial=dispatchTrial(trial,{type:'place',anchor:'stone_edge'},source,e10);
 e10=move(e10,{type:'walk',to:'stone_edge'});
 e10=move(e10,{type:'inspect',traceId:'surface'});
 trial=dispatchTrial(trial,{type:'compare'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,true);
 assert.match(viewTrial(trial,source,e10).feedback,/STILL UNKNOWN.*NOT DONE/);
 trial=dispatchTrial(trial,{type:'choose',question:'identity'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,false);
 trial=dispatchTrial(trial,{type:'place',anchor:'notice_wall'},source,e10);
 trial=dispatchTrial(trial,{type:'compare'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,false);
 e10=move(e10,{type:'walk',to:'entry'});
 e10=move(e10,{type:'walk',to:'notice_wall'});
 e10=move(e10,{type:'inspect',traceId:'holes'});
 trial=dispatchTrial(trial,{type:'compare'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,true);
 assert.deepEqual(replayTrial(trial.history,source,e10),trial);
 assert.deepEqual(restoreTrial(trial,source,e10),trial);
 trial=dispatchTrial(trial,{type:'remove'},source,e10);
 assert.equal(viewTrial(trial,source,e10).compared,false);
 assert.equal(viewTrial(trial,source,e10).anchor,null);
 assert.deepEqual(dispatchTrial(trial,{type:'reset'},source,e10),freshTrial());
});
test('upstream restart, invalid source and forged claims fail closed',()=>{
 const {e07,e08,e09}=sevenSceneUpstream(),source=questionSource(e07,e08,e09),e10=E10.fresh();
 assert.equal(questionSource(E07.dispatch(e07,{scene:'nav',type:'restart'}),e08,e09),null);
 assert.equal(questionSource(e07,e08,E09.dispatch(e09,{scene:'nav',type:'restart'})),null);
 assert.equal(questionSource(e07,e08,{...e09,rights:['hill-open']}),null);
 assert.equal(questionSource(null,e08,e09),null);
 assert.equal(replayTrial([{type:'grant-access'}],source,e10),null);
 assert.equal(replayTrial([{type:'choose',question:'access',approved:true}],source,e10),null);
 assert.equal(replayTrial([{type:'place',anchor:'upper_closed'}],source,e10),null);
 assert.equal(restoreTrial({...freshTrial(),compared:true},source,e10),null);
 assert.deepEqual(dispatchTrial(freshTrial(),{type:'choose',question:'Common'},source,e10),freshTrial());
 assert.equal(viewTrial(freshTrial(),null,e10),null);
});
